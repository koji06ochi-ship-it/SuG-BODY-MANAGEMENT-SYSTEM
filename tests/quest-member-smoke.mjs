import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const BASE=(process.env.SUG_BASE_URL||'http://127.0.0.1:8080').replace(/\/$/,'');
const browser=await chromium.launch({headless:true});
const context=await browser.newContext();
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(String(e)));
page.on('console',m=>{if(m.type()==='error') errors.push(m.text())});
await page.goto(`${BASE}/quest.html?smoke=${Date.now()}`,{waitUntil:'domcontentloaded'});
await page.waitForSelector('iframe',{timeout:10000});
const deadline=Date.now()+15000;let app=null;
while(Date.now()<deadline){app=page.frames().find(f=>/shrine-quest-v26\.5\.208\.html/.test(f.url()));if(app)break;await page.waitForTimeout(150)}
assert.ok(app,'QUEST iframe not loaded');
await app.waitForSelector('#today',{timeout:10000});
assert.ok(await app.locator('#today').isVisible(),'QUEST today not visible');
assert.match((await app.locator('#kitaProgress').innerText()).trim(),/北区 0\/11/);
assert.equal((await app.locator('#wallet').innerText()).trim(),'0 pt');
assert.match(await app.locator('#qShrine').innerText(),/大阪天満宮/);
await app.waitForSelector('#questCompanion',{timeout:5000});
assert.match(await app.locator('#questCompanion').innerText(),/相棒/);
await app.locator('#questGo').click();
assert.ok(await app.locator('#mapPage').isVisible(),'map page not visible');
await app.waitForSelector('.questCats',{timeout:5000});
assert.equal(await app.locator('.questCat').count(),8,'expected eight exploration category tabs');
const cats=await app.locator('.questCats').innerText();
for(const label of ['神社','史跡','マンホール','古墳','城・城跡','ご飯','買い物','体験']) assert.match(cats,new RegExp(label));
await app.getByRole('button',{name:'史跡',exact:true}).click();
assert.ok(await app.locator('#map').evaluate(el=>el.classList.contains('category-empty')),'non-shrine category should hide shrine pins');
assert.match(await app.locator('#categoryState').innerText(),/史跡/);
await app.getByRole('button',{name:/神社/,exact:true}).click();
assert.ok(!(await app.locator('#map').evaluate(el=>el.classList.contains('category-empty'))),'shrine category should restore shrine pins');
assert.match(await app.locator('.shrineExpand').innerText(),/磐船稲荷大明神/);
await app.waitForSelector('.pin.next',{timeout:5000});
await app.locator('[data-check="tenmangu"]').click();
assert.ok(await app.locator('#modal').evaluate(el=>el.classList.contains('on')),'unlock modal missing');
await app.locator('#closeModal').click();
assert.equal((await app.locator('#wallet').innerText()).trim(),'100 pt');
assert.match((await app.locator('#kitaProgress').innerText()).trim(),/北区 1\/11/);
assert.match(await app.locator('#qShrine').innerText(),/堀川神社/);
await app.locator('[data-page="relicPage"]').click();
assert.ok(await app.locator('#relicPage').isVisible());
assert.match(await app.locator('#relics').innerText(),/天満の天神章/);
await app.locator('[data-page="bookPage"]').click();
assert.match(await app.locator('#book').innerText(),/●公式確認/);
assert.equal(errors.length,0,`browser errors:\n${errors.join('\n')}`);
await browser.close();
console.log(`QUEST V26.5.212 PASS ${BASE}`);
